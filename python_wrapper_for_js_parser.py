import subprocess
import sys
import os
import json
import tempfile
from pathlib import Path
import argparse

# -----------------------------------------------------------------
# Extract comment lines from source code
# Supports:
#   - Single line comments (// ...)
#   - Block comments (/* ... */ and /** ... */)
#
# AST does not include comments as part of the code structure.
# To capture them, I must extract them manually from the source text.
# ------------------------------------------------------------------
def extract_comment_lines(code):
    in_block_comment = False # Track if we are inside a multi-line block comment
    comment_lines = [] # List of collected comment lines

    for line in code.splitlines():
        stripped = line.strip()

        # Check for single-line block comments (/* ... */ or /** ... */)
        if stripped.startswith("/*") and "*/" in stripped:
            comment_lines.append(line[:line.index("*/") + 2])
            continue

        # Start of multi-line block comment
        if stripped.startswith("/*"):
            in_block_comment = True
            comment_lines.append(line)
            continue

        # Inside a block comment
        if in_block_comment:
            comment_lines.append(line)
            if "*/" in stripped:
                in_block_comment = False
            continue

        # Handle single-line comments starting with //
        if stripped.startswith("//"):
            comment_lines.append(line)

    return comment_lines


# ----------------------------------------------------------------
# Wrapper for the JavaScript parser (Node.js + JSON transformation)
# ----------------------------------------------------------------
def run_js_parser(codebase_dir: str, output_dir: str | None = None, node_script: str = "babel_javascript_parser.js") -> tuple[Path, Path]:

    """
    Takes a local folder with JavaScript code,
    runs the Node.js parser script, and transforms the JSON
    into a standardized schema.

    Writes two JSON files:
      - static_analysis_output_javascript_lang.json (main analysis)
      - comments_only_javascript_lang.json (just comments)

    Returns:
      (path_to_main_json, path_to_comments_json)
    """
    
    # Resolve absolute path of the input folder
    codebase_root = Path(codebase_dir).resolve()

    # Default output directory: %TEMP%/kg_api_js/javascript/<repo_name>
    if output_dir is None:
        base_tmp = Path(os.getenv("KG_TMP_BASE", r"C:\kg_tmp"))
        output_dir = base_tmp / "kg_api_js" / "javascript" / codebase_root.name
    out_root = Path(output_dir).resolve()
    out_root.mkdir(parents=True, exist_ok=True) # ensure output folder exists

    # Define output file paths
    main_json     = out_root / "static_analysis_output_javascript_lang.json"
    comments_json = out_root / "comments_only_javascript_lang.json"

    # Run the Node.js parser script on the codebase.
    # It should produce "javascript_codebase_ast_analysis.json" in codebase_root.
    print(f"[node] node {node_script} {codebase_root}")
    try:
        subprocess.run(["node", node_script, str(codebase_root)], check=True)
    except subprocess.CalledProcessError as e:
        print(f"[ERROR] Node.js parser failed: {e}", file=sys.stderr)
        raise

    # Path to raw JSON file generated by Node.js
    raw_json = codebase_root / "javascript_codebase_ast_analysis.json"
    if not raw_json.exists():
        raise FileNotFoundError(f"JSON output file not found: {raw_json}")

    # Read the raw JSON output
    with open(raw_json, "r", encoding="utf-8") as f:
        data = json.load(f)

    # Container for final standardized output
    output = []

    # Container for extracted comments from all files
    comments_output = []

    # Process each file's analysis
    for filename, analysis in data.items():
        # Initialize schema for this file
        file_result = [
            {"file": os.path.basename(filename)},
            {"imports": analysis.get("imports", [])},
            {"global_variables": analysis.get("globalVariables", [])},
            {"functions": []},
            {"classes": []}
        ]

        # functions
        funcs_out = []
        for func in analysis.get("functions", []):
            func_info = {
                "name": func["name"],
                "params": func.get("arguments", []),          # map "arguments" -> "params"
                "local_variables": func.get("localVariables", [])  # map "localVariables" -> "local_variables"
            }
            funcs_out.append(func_info)
        file_result[3]["functions"] = funcs_out

        # classes
        classes_out = []
        for cls in analysis.get("classes", []):
            cls_info = {
                "name": cls["name"],
                "attributes": cls.get("attributes", []),
                "methods": []
            }
            # Process each method of the class
            for method in cls.get("methods", []):
                method_info = {
                    "name": method["name"],
                    "params": method.get("arguments", []),
                    "local_variables": method.get("localVariables", [])
                }
                cls_info["methods"].append(method_info)
            classes_out.append(cls_info)
        file_result[4]["classes"] = classes_out

        # Add this file's results to main output
        output.append(file_result)

        # ------------------------------------------------
        # Extract raw comments from the original source code
        # ------------------------------------------------
        src_path = (codebase_root / filename).resolve()

        try:
            with open(src_path, "r", encoding="utf-8") as src_file:
                code_text = src_file.read()
                comments = extract_comment_lines(code_text)
        except Exception as e:
            comments = [f"Error reading file {src_path}: {e}"]

        comments_output.append({
            "file": os.path.basename(filename),
            "comments": comments
        })


    # Write final JSON files
    with open(main_json, "w", encoding="utf-8") as out_f:
        json.dump(output, out_f, ensure_ascii=False, indent=2)

    with open(comments_json, "w", encoding="utf-8") as out_c:
        json.dump(comments_output, out_c, ensure_ascii=False, indent=2)

    print(f"[DONE] JSON: {main_json}")
    print(f"[DONE] Comments: {comments_json}")
    return main_json, comments_json


